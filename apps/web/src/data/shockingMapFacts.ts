// Global ring buffer to track the last 20 generated fact IDs to guarantee no repeats
const recentFactHistory: string[] = [];
const HISTORY_WINDOW_SIZE = 20;

/**
 * Get a randomized shocking fact from the 200+ database, guaranteed NOT to repeat
 * any of the last 15-20 generated facts.
 */
export function getRandomFact(pageTag?: string): ShockingFact {
  const historySet = new Set(recentFactHistory);

  // 1. Try to find a candidate matching pageTag that hasn't appeared recently
  let candidates: ShockingFact[] = [];
  if (pageTag) {
    candidates = SHOCKING_MAP_FACTS.filter(
      (f) => f.pageTag === pageTag && !historySet.has(f.id)
    );
  }

  // 2. If no page-specific un-seen candidate, pull from the entire global 200+ pool excluding recent history
  if (candidates.length === 0) {
    candidates = SHOCKING_MAP_FACTS.filter((f) => !historySet.has(f.id));
  }

  // 3. Fallback: if somehow history exhausts everything, reset history and use full pool
  if (candidates.length === 0) {
    recentFactHistory.length = 0;
    candidates = SHOCKING_MAP_FACTS;
  }

  // Pick random item from candidate pool
  const randomIndex = Math.floor(Math.random() * candidates.length);
  const chosenFact = candidates[randomIndex];

  // Record into history ring buffer
  recentFactHistory.push(chosenFact.id);
  if (recentFactHistory.length > HISTORY_WINDOW_SIZE) {
    recentFactHistory.shift(); // Remove oldest
  }

  return chosenFact;
}
